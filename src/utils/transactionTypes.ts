/** "CONSENSUSSUBMITMESSAGE" -> "Consensus submit message". Unknown parts are kept as they are. */
export const formatTransactionType = (type: string) => {
    const words: string[] = [];
    let rest = type.toUpperCase();
    while (rest) {
        const word = WORDS.find((w) => rest.startsWith(w));
        if (!word) {
            words.push(rest);
            break;
        }
        words.push(word);
        rest = rest.slice(word.length);
    }
    const sentence = words.join(" ").toLowerCase();
    return sentence.charAt(0).toUpperCase() + sentence.slice(1);
};
